const assert=require('node:assert/strict');
const dates=require('../period-dates.js');
const cycle=require('../cycle-model.js');
assert.equal(dates.parse('1.2.2026'),'2026-02-01');
assert.equal(dates.parse('01022026'),'2026-02-01');
assert.equal(dates.parse('2026-02-01'),'2026-02-01');
assert.equal(dates.format('2026-02-01'),'01.02.2026');
for(const value of ['31.04.2026','29.02.2026','1.1.26','2026-13-01','abc','',null])assert.equal(dates.parse(value),null,value);
assert.equal(dates.parse('29.02.2024'),'2024-02-29');
const validate=(start,end,rest={})=>dates.validate({start,end,today:'2026-11-04',...rest});
assert.equal(validate('2026-10-01',null),'');
assert.equal(validate('2026-10-01','2026-10-05'),'');
assert.ok(validate('2026-10-05','2026-10-01'));
assert.ok(validate('2026-11-05',null));
assert.ok(validate('2026-10-01','2026-11-05'));
assert.ok(validate('2026-10-01','2026-10-21',{periods:['2026-10-01','2026-10-20']}));
assert.ok(validate('2026-10-03',null,{periods:['2026-10-01'],ends:{'2026-10-01':'2026-10-05'}}));
assert.equal(validate('2026-10-20',null,{periods:['2026-10-01'],ends:{}}),'');
assert.equal(dates.days('2026-10-24','2026-10-26'),3);
const base={date:'2026-11-04',periods:['2026-10-01'],length:32,periodLength:5,predict:true};
assert.equal(cycle.snapshot(base).day,35);assert.equal(cycle.snapshot(base).overdue,2);
assert.deepEqual(cycle.snapshot({...base,periodEnds:{'2026-10-01':'2026-10-05'}}),cycle.snapshot(base));
assert.equal(cycle.snapshot({...base,periods:[...base.periods,'2026-11-04']}).day,1);
console.log('PASS: dotted/digit/native dates, leap/future/range/overlap checks, inclusive end dates, 32-day delay independent of end, reset only by a new start');
