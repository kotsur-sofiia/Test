const assert=require('node:assert/strict');const {parse}=require('../capture-parser.js');
const date='2026-11-01',products=[{id:'salmon',name:'Лосось'},{id:'rice',name:'Рис'},{id:'broccoli',name:'Брокколи'}];
const p=t=>parse(t,date,products);
assert.equal(p('Ела лосось триста грамм')[0].grams,300);
const food=p('съел рыбу 200 грамм, рис 100 грамм, овощи на пару, брокколи 100 грамм');
assert.deepEqual(food.map(x=>x.kind),['food','food','note','food']);assert.equal(food[0].product,'');assert.equal(food[1].product,'rice');assert.equal(food[2].section,'food');
assert.equal(p('Спала с восьми до шести')[0].start,'');
const sleep=p('Спала с 23:00 до 07:00')[0];assert.equal(sleep.start,'2026-10-31T23:00');assert.equal(sleep.end,'2026-11-01T07:00');
assert.equal(p('Проснулась в семь утра')[0].at,date+'T07:00');
assert.equal(p('Проснулась в семь часов тридцать минут')[0].at,date+'T07:30');
assert.equal(p('Вчера проснулась в 7:00')[0].date,'2026-10-31');
assert.equal(p('Силовая тренировка один час')[0].minutes,60);
assert.equal(p('Йога 1 час 30 минут')[0].minutes,90);
assert.equal(p('Выпила воды 0,5 литра')[0].ml,500);
assert.deepEqual(p('Ела лосось 300 грамм. Проснулась в 7:00. Силовая тренировка 1 час.').map(x=>x.kind),['food','sleep-event','workout']);
for(const t of ['Не ела лосось 300 грамм','Завтра буду есть рис 100 грамм','Не спала с 23:00 до 07:00','Хочу пойти на тренировку'])assert.equal(p(t)[0].kind,'note',t);
assert.equal(p('Моя свободная заметка')[0].kind,'note');
assert.equal(p('Ела лосось 0.3 кг')[0].grams,300);
console.log('PASS: requested mixed phrases, food portions, unknown fish, dates and overnight sleep, ambiguous hours, standalone wake-up, spoken numbers, workouts, water, negation/future notes');
